// 32×48 pixel sprites — 中国武侠 2D 唯美风格

function blank(w, h) {
  return Array.from({ length: h }, () => Array(w).fill(0));
}

function stamp(grid, pixels, ox, oy) {
  for (let y = 0; y < pixels.length; y++) {
    for (let x = 0; x < pixels[y].length; x++) {
      const gy = oy + y;
      const gx = ox + x;
      if (gy >= 0 && gy < grid.length && gx >= 0 && gx < grid[0].length && pixels[y][x]) {
        grid[gy][gx] = pixels[y][x];
      }
    }
  }
}

